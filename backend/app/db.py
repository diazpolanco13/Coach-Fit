ENV_PATH = Path(__file__).resolve().parent.parent / ".env"


def _load_env_file() -> None:
    """Lee backend/.env sin depender de python-dotenv. Las variables ya
    presentes en el entorno ganan, para que Dokploy pueda inyectar las suyas."""
    if not ENV_PATH.exists():
        return
    for raw in ENV_PATH.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


def database_url() -> str:
    _load_env_file()
    url = os.getenv("DATABASE_URL", "").strip()
    if not url:
        raise RuntimeError(
            "Falta DATABASE_URL. Definela en el entorno o en backend/.env, p.ej.\n"
            "  DATABASE_URL=postgresql://usuario:clave@127.0.0.1:5432/coachfit"
        )
    return url


_pool: ConnectionPool | None = None


def _get_pool() -> ConnectionPool:
    global _pool
    if _pool is None:
        pool = ConnectionPool(
            database_url(),
            min_size=1,
            max_size=10,
            kwargs={"row_factory": dict_row},
            open=False,
        )
        pool.open(wait=True, timeout=30)
        _pool = pool
    return _pool


def close_pool() -> None:
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None


@contextmanager
def get_db() -> Iterator[psycopg.Connection]:
    """Una conexion del pool por operacion. El context manager de psycopg hace
    commit al salir sin error y rollback si hay excepcion, igual que la version
    sqlite que esto reemplaza."""
    with _get_pool().connection() as conn:
        yield conn


# Postgres siempre aplica las claves foraneas, asi que no hay equivalente del
# PRAGMA foreign_keys que usaba la version sqlite.
SCHEMA = """
CREATE TABLE IF NOT EXISTS body_metrics (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TEXT NOT NULL,
  weight_kg DOUBLE PRECISION,
  body_fat_pct DOUBLE PRECISION,
  notes TEXT,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS runs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TEXT NOT NULL,
  distance_km DOUBLE PRECISION NOT NULL,
  duration_min DOUBLE PRECISION,
  pace_min_per_km DOUBLE PRECISION,
  rpe INTEGER,
  notes TEXT,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TEXT NOT NULL UNIQUE,
  focus TEXT,
  completed INTEGER NOT NULL DEFAULT 0,
  session_rpe INTEGER,
  notes TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS session_sets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id INTEGER NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
  exercise_id TEXT NOT NULL,
  set_index INTEGER NOT NULL,
  reps INTEGER,
  weight_kg DOUBLE PRECISION,
  rpe INTEGER,
  done INTEGER NOT NULL DEFAULT 1,
  notes TEXT
);

CREATE TABLE IF NOT EXISTS week_plan (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  payload TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS coach_notes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TEXT NOT NULL,
  week_start TEXT NOT NULL,
  prompt_summary TEXT,
  advice TEXT NOT NULL,
  source TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS user_equipment (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  equipment_type TEXT NOT NULL,
  weight_kg DOUBLE PRECISION,
  quantity INTEGER DEFAULT 1,
  created_at TEXT NOT NULL
);

-- Multiples planes guardados, uno activo. Sustituye al singleton week_plan,
-- que queda como legado de solo lectura: sin sistema de migraciones lo unico
-- seguro es crear tablas nuevas, nunca alterar las que ya tienen datos.
CREATE TABLE IF NOT EXISTS plans (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  payload TEXT NOT NULL,
  is_active INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- Nombres unicos sin distinguir mayusculas: "Piernas" y "piernas" son el mismo
-- plan para el usuario.
CREATE UNIQUE INDEX IF NOT EXISTS plans_name_unique ON plans (lower(name));

-- Como maximo un plan activo, garantizado por la base y no solo por la app. El
-- indice parcial obliga a apagar el activo antes de encender el nuevo.
CREATE UNIQUE INDEX IF NOT EXISTS plans_single_active
  ON plans (is_active) WHERE is_active = 1;

-- Espacios de entrenamiento («gimnasios virtuales»): casa, gimnasio comercial,
-- parque, hotel, oficina. El equipo deja de ser global y pasa a colgar de uno de
-- estos. user_equipment queda intacta como legado de solo lectura, igual que
-- week_plan: sin sistema de migraciones lo unico seguro es crear tablas nuevas.
CREATE TABLE IF NOT EXISTS gyms (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  -- hogar|comercial|outdoor|temporal|oficina. Deliberadamente SIN CHECK: una
  -- restriccion de enumerado sobre una tabla ya creada no se puede ampliar sin
  -- ALTER, y esta lista va a crecer. Se valida en gyms.normalize_kind().
  kind TEXT NOT NULL DEFAULT 'hogar',
  icon TEXT,
  color TEXT,
  notes TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- Nombres unicos sin distinguir mayusculas, igual que plans_name_unique. Ademas
-- es lo que hace segura la siembra concurrente en bootstrap_gyms().
CREATE UNIQUE INDEX IF NOT EXISTS gyms_name_unique ON gyms (lower(name));

-- Inventario por espacio. Mismas columnas que user_equipment mas gym_id, para
-- que el backfill sea una copia columna a columna y el tipo del frontend no
-- cambie de forma. Aqui quantity SI es NOT NULL: la tabla vieja lo dejo
-- nullable y el copiado lo arregla con COALESCE.
CREATE TABLE IF NOT EXISTS gym_equipment (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gym_id INTEGER NOT NULL REFERENCES gyms(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  equipment_type TEXT NOT NULL,
  weight_kg DOUBLE PRECISION,
  quantity INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL
);

-- Cubre el filtro por espacio y el ORDER BY del listado a la vez.
CREATE INDEX IF NOT EXISTS gym_equipment_by_gym
  ON gym_equipment (gym_id, equipment_type, name);

-- Curacion de la biblioteca, ESPARCIDA a proposito: solo se guardan las marcas
-- explicitas («favorito» y «oculto»). «disponible» es el estado por defecto de
-- todo lo que el inventario permite y NUNCA ocupa una fila — con 1324
-- ejercicios y varios espacios seria repetir miles de veces el valor por
-- defecto. Ese invariante lo sostiene db.set_exercise_pref(), no la base.
CREATE TABLE IF NOT EXISTS gym_exercise_prefs (
  gym_id INTEGER NOT NULL REFERENCES gyms(id) ON DELETE CASCADE,
  -- Sin FK: el catalogo es un JSON, no una tabla. Misma decision que
  -- session_sets.exercise_id.
  exercise_id TEXT NOT NULL,
  state TEXT NOT NULL,
  created_at TEXT NOT NULL,
  -- Clave natural: nada referencia una marca por id propio. Da gratis el
  -- barrido por gym_id y el destino del upsert.
  PRIMARY KEY (gym_id, exercise_id)
);
"""


def init_db() -> None:
    with get_db() as conn:
        conn.execute(SCHEMA)


def now_iso() -> str:
    return datetime.now().isoformat(timespec="seconds")


def upsert_session(
    day: str,
    *,
    focus: str | None = None,
    completed: bool | None = None,
    session_rpe: int | None = None,
    notes: str | None = None,
) -> dict[str, Any]:
    with get_db() as conn:
        row = conn.execute("SELECT * FROM sessions WHERE date = %s", (day,)).fetchone()
        ts = now_iso()
        if row is None:
            conn.execute(
                """
                INSERT INTO sessions (date, focus, completed, session_rpe, notes, created_at, updated_at)
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    day,
                    focus,
                    1 if completed else 0,
                    session_rpe,
                    notes,
                    ts,
                    ts,
                ),
            )
        else:
            # Los casts explicitos evitan que Postgres se quede sin tipo cuando el
            # parametro llega NULL dentro de un COALESCE.
            conn.execute(
                """
                UPDATE sessions
                SET focus = COALESCE(%s::text, focus),
                    completed = COALESCE(%s::integer, completed),
                    session_rpe = COALESCE(%s::integer, session_rpe),
                    notes = COALESCE(%s::text, notes),
                    updated_at = %s
                WHERE date = %s
                """,
                (
                    focus,
                    None if completed is None else (1 if completed else 0),
                    session_rpe,
                    notes,
                    ts,
                    day,
                ),
            )
        return dict(conn.execute("SELECT * FROM sessions WHERE date = %s", (day,)).fetchone())


def replace_session_sets(session_id: int, sets: list[dict[str, Any]]) -> list[dict[str, Any]]:
    with get_db() as conn:
        conn.execute("DELETE FROM session_sets WHERE session_id = %s", (session_id,))
        for s in sets:
            conn.execute(
                """
                INSERT INTO session_sets
                (session_id, exercise_id, set_index, reps, weight_kg, rpe, done, notes)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    session_id,
                    s["exercise_id"],
                    s["set_index"],
                    s.get("reps"),
                    s.get("weight_kg"),
                    s.get("rpe"),
                    1 if s.get("done", True) else 0,
                    s.get("notes"),
                ),
            )
        rows = conn.execute(
            "SELECT * FROM session_sets WHERE session_id = %s ORDER BY exercise_id, set_index",
            (session_id,),
        ).fetchall()
        return [dict(r) for r in rows]


def get_session(day: str) -> dict[str, Any] | None:
    with get_db() as conn:
        row = conn.execute("SELECT * FROM sessions WHERE date = %s", (day,)).fetchone()
        if not row:
            return None
        sets = conn.execute(
            "SELECT * FROM session_sets WHERE session_id = %s ORDER BY exercise_id, set_index",
            (row["id"],),
        ).fetchall()
        out = dict(row)
        out["completed"] = bool(out["completed"])
        out["sets"] = [dict(s) | {"done": bool(s["done"])} for s in sets]
        return out


def list_sessions(start: str, end: str) -> list[dict[str, Any]]:
    with get_db() as conn:
        # SUM y AVG devuelven numeric en Postgres; sin el cast a double precision
        # llegarian como Decimal y romperian la aritmetica de compute_weekly_load.
        rows = conn.execute(
            """
            SELECT s.*,
              CAST(COALESCE(SUM(ss.reps * COALESCE(ss.weight_kg, 0)), 0) AS DOUBLE PRECISION) AS volume_kg,
              COUNT(ss.id) AS set_count,
              CAST(AVG(ss.rpe) AS DOUBLE PRECISION) AS avg_set_rpe
            FROM sessions s
            LEFT JOIN session_sets ss ON ss.session_id = s.id AND ss.done = 1
            WHERE s.date BETWEEN %s AND %s
            GROUP BY s.id
            ORDER BY s.date
            """,
            (start, end),
        ).fetchall()
        out = []
        for r in rows:
            d = dict(r)
            d["completed"] = bool(d["completed"])
            out.append(d)
        return out


