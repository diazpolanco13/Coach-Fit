def bootstrap_plans() -> None:
    """Idempotente: corre en cada arranque y solo hace algo la primera vez.

    1. Si `plans` esta vacia, copia el singleton week_plan -que en produccion
       tiene la rutina real del usuario- como primer plan y lo deja activo. La
       fila de week_plan NO se borra ni se modifica.
    2. Si no habia week_plan (base nueva), siembra el plan por defecto del
       catalogo.
    3. Garantiza que siempre haya exactamente un plan activo, tambien si alguien
       apago el flag a mano.
    """
    from . import catalog
    from . import plans as plans_mod

    if count_plans() == 0:
        with get_db() as conn:
            legacy = conn.execute(
                "SELECT payload, updated_at FROM week_plan WHERE id = 1"
            ).fetchone()
            source = json.loads(legacy["payload"]) if legacy else catalog.default_week()
            doc = plans_mod.normalize_plan_payload(source)
            ts = now_iso()
            conn.execute(
                """
                INSERT INTO plans (name, payload, is_active, created_at, updated_at)
                VALUES (%s, %s, 1, %s, %s)
                ON CONFLICT (lower(name)) DO NOTHING
                """,
                (
                    doc["name"],
                    json.dumps(doc, ensure_ascii=False),
                    # created_at hereda la fecha de la fila vieja: el plan no se
                    # creo el dia del despliegue.
                    legacy["updated_at"] if legacy else ts,
                    ts,
                ),
            )

    with get_db() as conn:
        active = conn.execute(
            "SELECT COUNT(*) AS n FROM plans WHERE is_active = 1"
        ).fetchone()["n"]
        if not active:
            first = conn.execute("SELECT id FROM plans ORDER BY id LIMIT 1").fetchone()
            if first:
                _activate_in_conn(conn, first["id"])


