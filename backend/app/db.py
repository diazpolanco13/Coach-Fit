def _upsert_imported_body_metric_in_conn(
    conn: psycopg.Connection, payload: dict[str, Any]
) -> tuple[dict[str, Any], bool]:
    """Devuelve (fila, created). created=True solo si fue INSERT, no UPDATE."""
    uid = require_uid()
