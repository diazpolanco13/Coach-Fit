def _parse_float(raw: Any) -> float | None:
    if raw is None:
        return None
    value = str(raw).strip().replace(",", ".")
    if not value:
        return None
    try:
        return float(value)
    except ValueError:
        return None


def _parse_renpho_date(raw: str) -> str:
    return datetime.strptime(raw.strip(), "%m/%d/%y").date().isoformat()


def _parse_renpho_time(raw: str | None) -> str | None:
    if not raw:
        return None
    value = raw.strip().lower().replace("\u202f", " ").replace("\xa0", " ")
    value = value.replace("a.m.", "AM").replace("p.m.", "PM")
    value = value.replace("a. m.", "AM").replace("p. m.", "PM")
    try:
        return datetime.strptime(value, "%I:%M:%S %p").time().isoformat()
    except ValueError:
        return raw.strip()


