def update_user_fields(user_id: int, fields: dict[str, Any]) -> dict[str, Any] | None:
    """Solo se llama con un dict ya filtrado por el endpoint segun el rol de quien
    pide. Nunca con lo que mande el cliente sin filtrar."""
    allowed = ("email", "full_name", "role", "trainer_id", "is_active")
    changes = {k: v for k, v in fields.items() if k in allowed}
    if not changes:
        return get_user(user_id)
    columns = tuple(changes)
    assignments = ", ".join(f"{col} = %s" for col in columns)
    with get_db() as conn:
        row = conn.execute(
            f"UPDATE users SET {assignments}, updated_at = %s WHERE id = %s "
            f"RETURNING {_USER_COLS}",
            tuple(changes[col] for col in columns) + (now_iso(), user_id),
        ).fetchone()
        return dict(row) if row else None


