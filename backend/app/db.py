def resolve_gym_id(explicit: int | None = None) -> int | None:
    """El espacio que rige AHORA. Por orden:

      1. el que pida el cliente — es el cambio de espacio para una sesion
         suelta, que a proposito no se persiste en ningun sitio;
      2. el del plan activo;
      3. el primero que exista, para que nada reviente si el plan apunta a un
         espacio borrado o todavia no tiene ancla.

    Devuelve None solo si no hay ni un espacio, que tras bootstrap_gyms() no
    deberia pasar. No hay columna `is_default` a proposito: un flag puede
    desincronizarse del plan activo y crea la pregunta «cual gana» en cada
    endpoint.
    """
    if explicit is not None and gym_exists(explicit):
        return explicit
    active = get_active_plan()
    anchored = (active or {}).get("payload", {}).get("gym_id")
    if anchored is not None and gym_exists(anchored):
        return anchored
    with get_db() as conn:
        row = conn.execute(
            "SELECT id FROM gyms WHERE user_id = %s ORDER BY id LIMIT 1",
            (require_uid(),),
        ).fetchone()
    return row["id"] if row else None


