def get_strength_prs(start: str, end: str, limit: int = 8) -> list[dict[str, Any]]:
    """Best all-time weight records reached inside the selected window."""
    uid = require_uid()
    with get_db() as conn:
        rows = conn.execute(
            """
            WITH window_max AS (
              SELECT ss.exercise_id, MAX(ss.weight_kg) AS max_weight
              FROM session_sets ss
              JOIN sessions s ON s.id = ss.session_id
              WHERE s.date BETWEEN %s AND %s AND ss.weight_kg > 0
                AND ss.done = 1 AND s.completed = 1 AND s.user_id = %s
              GROUP BY ss.exercise_id
            ),
            prior_max AS (
              SELECT ss.exercise_id, MAX(ss.weight_kg) AS max_weight
              FROM session_sets ss
              JOIN sessions s ON s.id = ss.session_id
              WHERE s.date < %s AND ss.weight_kg > 0
                AND ss.done = 1 AND s.completed = 1 AND s.user_id = %s
              GROUP BY ss.exercise_id
            ),
            winners AS (
              SELECT DISTINCT ON (ss.exercise_id)
                ss.exercise_id, s.date, ss.weight_kg, ss.reps
              FROM session_sets ss
              JOIN sessions s ON s.id = ss.session_id
              JOIN window_max w
                ON w.exercise_id = ss.exercise_id AND w.max_weight = ss.weight_kg
              WHERE s.date BETWEEN %s AND %s
                AND ss.done = 1 AND s.completed = 1 AND s.user_id = %s
              ORDER BY ss.exercise_id, s.date DESC, ss.reps DESC NULLS LAST
            )
            SELECT w.exercise_id, w.date, w.weight_kg, w.reps,
              p.max_weight AS previous_weight
            FROM winners w
            LEFT JOIN prior_max p ON p.exercise_id = w.exercise_id
            WHERE p.max_weight IS NULL OR w.weight_kg > p.max_weight
            ORDER BY w.date DESC, w.weight_kg DESC
            LIMIT %s
            """,
            (start, end, uid, start, uid, start, end, uid, limit),
        ).fetchall()
    return [
        {
            "exercise_id": row["exercise_id"],
            "date": row["date"],
            "weight_kg": float(row["weight_kg"]),
            "reps": int(row["reps"]) if row["reps"] is not None else None,
            "previous_weight_kg": (
                float(row["previous_weight"]) if row["previous_weight"] is not None else None
            ),
        }
        for row in rows
    ]


def compute_weekly_load(start: str, end: str) -> dict[str, Any]:
    uid = require_uid()
    sessions = list_sessions(start, end)
    with get_db() as conn:
        runs = conn.execute(
            "SELECT * FROM runs WHERE user_id = %s AND date BETWEEN %s AND %s ORDER BY date",
            (uid, start, end),
        ).fetchall()
        weights = conn.execute(
            "SELECT * FROM body_metrics WHERE user_id = %s AND date BETWEEN %s AND %s ORDER BY date",
            (uid, start, end),
        ).fetchall()

    completed = [s for s in sessions if s["completed"]]
    volume = sum(float(s["volume_kg"] or 0) for s in completed)
    set_count = sum(int(s["set_count"] or 0) for s in completed)
    rpes = [s["session_rpe"] for s in completed if s.get("session_rpe")]
    set_rpes = [s["avg_set_rpe"] for s in completed if s.get("avg_set_rpe")]
    run_km = sum(float(r["distance_km"] or 0) for r in runs)
    avg_session_rpe = sum(rpes) / len(rpes) if rpes else None
    avg_set_rpe = sum(set_rpes) / len(set_rpes) if set_rpes else None

    # Simple strain index: volume tonnage + run load + RPE factor
    rpe_factor = (avg_session_rpe or avg_set_rpe or 5) / 10
    strain = round((volume / 1000) + (run_km * 2) + (len(completed) * 3 * rpe_factor), 1)

    return {
        "week_start": start,
        "week_end": end,
        "training_days": len(completed),
        "planned_or_logged_days": len(sessions),
        "total_volume_kg": round(volume, 1),
        "total_sets": set_count,
        "avg_session_rpe": round(avg_session_rpe, 1) if avg_session_rpe else None,
        "avg_set_rpe": round(avg_set_rpe, 1) if avg_set_rpe else None,
        "run_distance_km": round(run_km, 2),
        "run_count": len(runs),
        "strain_index": strain,
        "body_weights": [dict(w) for w in weights],
        "sessions": sessions,
        "runs": [dict(r) for r in runs],
    }


def _monday(d: date) -> date:
    return d - timedelta(days=d.weekday())


def _planned_sets(day: dict[str, Any]) -> int:
    return sum(max(0, int(item.get("sets") or 0)) for item in day.get("items", []))


def _completion_pct(done_sets: int, planned_sets: int) -> int:
    if planned_sets <= 0:
        return 0
    return round(min(done_sets / planned_sets, 1) * 100)


def _metric_delta(latest: dict[str, Any] | None, oldest: dict[str, Any] | None) -> dict[str, float | None]:
    if not latest or not oldest:
        return {"weight_kg": None, "body_fat_pct": None, "muscle_pct": None}
    out: dict[str, float | None] = {}
    for field in ("weight_kg", "body_fat_pct", "muscle_pct"):
        a, b = latest.get(field), oldest.get(field)
        out[field] = round(float(a) - float(b), 2) if a is not None and b is not None else None
    return out


def profile_summary(window_days: int = 28) -> dict[str, Any]:
    window_days = max(7, min(window_days, 180))
    end_d = today_local()
    start_d = end_d - timedelta(days=window_days - 1)
    start, end = start_d.isoformat(), end_d.isoformat()
    calendar_start_d = _monday(start_d)
    calendar_end_d = _monday(end_d) + timedelta(days=6)
    sessions = list_sessions(calendar_start_d.isoformat(), calendar_end_d.isoformat())
    sessions_by_date = {date.fromisoformat(s["date"]): s for s in sessions}
    done_by_date = get_done_counts_by_date(
        calendar_start_d.isoformat(), calendar_end_d.isoformat()
    )
    trained_dates: set[date] = set()
    plan = load_active_plan() or {"days": []}
    plan_days_by_weekday = {
        int(d["weekday"]): d for d in plan.get("days", []) if _planned_sets(d) > 0
    }
    planned_sets_by_weekday = {
        wd: _planned_sets(d) for wd, d in plan_days_by_weekday.items()
    }
    planned_weekdays = set(planned_sets_by_weekday)

    weeks: dict[str, dict[str, Any]] = {}
    calendar: list[dict[str, Any]] = []
    planned_count = 0
    completed_on_plan = 0
    total_volume = 0.0
    cursor = calendar_start_d
    while cursor <= calendar_end_d:
        week_key = _monday(cursor).isoformat()
        in_window = start_d <= cursor <= end_d
        planned = cursor.weekday() in planned_weekdays
        planned_sets = planned_sets_by_weekday.get(cursor.weekday(), 0)
        sess = sessions_by_date.get(cursor)
        completed = bool(sess and sess["completed"])
        done_sets = int(sess.get("set_count") or 0) if sess else 0
        completion_pct = _completion_pct(done_sets, planned_sets)
        volume = float(sess.get("volume_kg") or 0) if completed and sess else 0.0
        plan_day = plan_days_by_weekday.get(cursor.weekday(), {"items": []})
        status = plan_day_training_status(
            items=plan_day.get("items") or [],
            done_by_exercise=done_by_date.get(cursor.isoformat(), {}),
            skips=(sess or {}).get("exercise_skips") if sess else None,
            feedback=(sess or {}).get("exercise_feedback") if sess else None,
            day_date=cursor,
            today=end_d,
            sess_completed=completed,
        )
        # Racha y «días entrenados»: series hechas, o día marcado hecho
        # (completed/bonus). Un parcial con series cuenta; un marcado vacío
        # también (el usuario afirmó el día). Los missed no.
        if in_window and (done_sets > 0 or status in ("completed", "bonus")):
            trained_dates.add(cursor)

        calendar.append(
            {
                "date": cursor.isoformat(),
                "weekday": cursor.weekday(),
                "planned": planned,
                "completed": completed,
                "status": status,
                "planned_sets": planned_sets,
                "done_sets": done_sets,
                "completion_pct": completion_pct,
                "volume_kg": round(volume, 1),
                "focus": sess.get("focus") if sess else None,
            }
        )

        if in_window:
            weeks.setdefault(
                week_key,
                {
                    "week_start": week_key,
                    "planned_days": 0,
                    "completed_days": 0,
                    "missed_dates": [],
                    "partial_dates": [],
                    "debt_sets": 0,
                    "volume_kg": 0.0,
                },
            )
            if planned:
                planned_count += 1
                weeks[week_key]["planned_days"] += 1
                if status == "completed":
                    completed_on_plan += 1
                    weeks[week_key]["completed_days"] += 1
                elif status == "partial":
                    weeks[week_key]["partial_dates"].append(cursor.isoformat())
                    weeks[week_key]["debt_sets"] += max(0, planned_sets - done_sets)
                elif status == "missed":
                    weeks[week_key]["missed_dates"].append(cursor.isoformat())
            # Los extras no inflan el numerador de «hechos/planificados»:
            # 1/5 por un domingo marcado vacío mentía sobre la semana.
            if completed:
                weeks[week_key]["volume_kg"] += volume
                total_volume += volume
        cursor += timedelta(days=1)

    streak = 0
    cursor = end_d
    while cursor in trained_dates:
        streak += 1
        cursor -= timedelta(days=1)

    with get_db() as conn:
        body_rows = conn.execute(
            """
            SELECT * FROM body_metrics
            WHERE user_id = %s AND date BETWEEN %s AND %s
            ORDER BY date ASC, measured_at ASC NULLS LAST, id ASC
            """,
            (require_uid(), start, end),
        ).fetchall()

    body = [dict(r) for r in body_rows]
    with get_db() as conn:
        _attach_body_metric_photos(conn, body)
    oldest = body[0] if body else None
    latest = body[-1] if body else None
    adherence = round(100 * completed_on_plan / planned_count) if planned_count else 0
    current_week = _monday(end_d).isoformat()
    previous_week = (_monday(end_d) - timedelta(days=7)).isoformat()

    def week_detail(week_start: str) -> dict[str, Any]:
        week = weeks.get(
            week_start,
            {
                "week_start": week_start,
                "planned_days": 0,
                "completed_days": 0,
                "missed_dates": [],
                "partial_dates": [],
                "debt_sets": 0,
                "volume_kg": 0.0,
            },
        )
        return {
            "week_start": week_start,
            "planned_days": week["planned_days"],
            "completed_days": week["completed_days"],
            "missed_dates": week["missed_dates"],
            "partial_dates": week["partial_dates"],
            "debt_sets": week["debt_sets"],
            "volume_kg": round(float(week["volume_kg"]), 1),
        }

    return {
        "window_days": window_days,
        "start": start,
        "end": end,
        "calendar": calendar,
        "week_compare": {
            "current": week_detail(current_week),
            "previous": week_detail(previous_week),
        },
        "consistency": {
            "planned_days": planned_count,
            "completed_days": len(trained_dates),
            "completed_planned_days": completed_on_plan,
            "adherence_pct": min(100, adherence),
            "current_streak_days": streak,
        },
        "volume": {
            "total_volume_kg": round(total_volume, 1),
            "weeks": [
                {
                    "week_start": week["week_start"],
                    "planned_days": week["planned_days"],
                    "completed_days": week["completed_days"],
                    "volume_kg": round(float(week["volume_kg"]), 1),
                }
                for week in sorted(weeks.values(), key=lambda w: w["week_start"])
            ],
        },
        "composition": {
            "latest": latest,
            "oldest": oldest,
            "delta": _metric_delta(latest, oldest),
        },
    }


