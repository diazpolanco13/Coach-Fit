def _load_env_file() -> None:
    """Lee backend/.env sin depender de python-dotenv. Las variables ya
    presentes en el entorno ganan, para que Dokploy pueda inyectar las suyas."""
    if not ENV_PATH.exists():
        return
    for raw in ENV_PATH.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


def database_url() -> str:
    _load_env_file()
    url = os.getenv("DATABASE_URL", "").strip()
    if not url:
        raise RuntimeError(
            "Falta DATABASE_URL. Definela en el entorno o en backend/.env, p.ej.\n"
            "  DATABASE_URL=postgresql://usuario:clave@127.0.0.1:5432/coachfit"
        )
    return url


_pool: ConnectionPool | None = None


def _get_pool() -> ConnectionPool:
    global _pool
    if _pool is None:
        pool = ConnectionPool(
            database_url(),
            min_size=1,
            max_size=10,
            kwargs={"row_factory": dict_row},
            open=False,
        )
        pool.open(wait=True, timeout=30)
        _pool = pool
    return _pool


def close_pool() -> None:
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None


@contextmanager
def get_db() -> Iterator[psycopg.Connection]:
    """Una conexion del pool por operacion. El context manager de psycopg hace
    commit al salir sin error y rollback si hay excepcion, igual que la version
    sqlite que esto reemplaza."""
    with _get_pool().connection() as conn:
        yield conn


# Dueño de los datos en el hilo/request actual. Lo pone el middleware de auth
# (o ensure_user_workspace / as_user en bootstrap). Las tablas OWNED_TABLES
# filtran y escriben con require_uid(); sin contexto fallan en alto.
_data_user_id: ContextVar[int | None] = ContextVar("data_user_id", default=None)


def set_data_user(user_id: int) -> Token[int | None]:
    return _data_user_id.set(user_id)


def reset_data_user(token: Token[int | None]) -> None:
    _data_user_id.reset(token)


def current_uid() -> int | None:
    return _data_user_id.get()


@contextmanager
def as_user(user_id: int) -> Iterator[None]:
    token = set_data_user(user_id)
    try:
        yield
    finally:
        reset_data_user(token)


def require_uid() -> int:
    uid = _data_user_id.get()
    if uid is None:
        raise RuntimeError(
            "Operacion de datos sin usuario de contexto. "
            "Llama set_data_user()/as_user() antes de tocar tablas OWNED."
        )
    return uid


