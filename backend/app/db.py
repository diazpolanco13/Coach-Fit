def gym_exists(gym_id: int) -> bool:
    with get_db() as conn:
        return conn.execute("SELECT 1 FROM gyms WHERE id = %s", (gym_id,)).fetchone() is not None


def gym_name_taken(name: str, *, exclude_id: int | None = None) -> bool:
    with get_db() as conn:
        # El cast explicito evita que Postgres se quede sin tipo con NULL.
        row = conn.execute(
            "SELECT id FROM gyms WHERE lower(name) = lower(%s) "
            "AND (%s::integer IS NULL OR id <> %s::integer)",
            (name.strip(), exclude_id, exclude_id),
        ).fetchone()
    return row is not None


def unique_gym_copy_name(base: str) -> str:
    from . import gyms as gyms_mod

    stem = base.strip()[: gyms_mod.MAX_GYM_NAME - 15]
    with get_db() as conn:
        taken = {r["n"] for r in conn.execute("SELECT lower(name) AS n FROM gyms").fetchall()}
    candidate, i = f"{stem} (copia)", 2
    while candidate.casefold() in taken:
        candidate, i = f"{stem} (copia {i})", i + 1
    return candidate


def create_gym(fields: dict[str, Any]) -> dict[str, Any]:
    from . import gyms as gyms_mod

    doc = gyms_mod.normalize_gym_fields(fields)
    ts = now_iso()
    with get_db() as conn:
        row = conn.execute(
            """
            INSERT INTO gyms (name, kind, icon, color, notes, created_at, updated_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s) RETURNING *
            """,
            (doc["name"], doc["kind"], doc["icon"], doc["color"], doc["notes"], ts, ts),
        ).fetchone()
    return dict(row)


def update_gym(gym_id: int, patch: dict[str, Any]) -> dict[str, Any] | None:
    """Parcial: lo que no venga en `patch` se conserva. El COALESCE deja pasar
    el borrado explicito de icon/color/notes mandando cadena vacia, que
    normalize_gym_fields convierte en None."""
    from . import gyms as gyms_mod

    current = get_gym(gym_id)
    if current is None:
        return None
    merged = {**current, **{k: v for k, v in patch.items() if v is not None}}
    doc = gyms_mod.normalize_gym_fields(merged)
    with get_db() as conn:
        row = conn.execute(
            """
            UPDATE gyms SET name = %s, kind = %s, icon = %s, color = %s,
                            notes = %s, updated_at = %s
            WHERE id = %s RETURNING *
            """,
            (doc["name"], doc["kind"], doc["icon"], doc["color"], doc["notes"], now_iso(), gym_id),
        ).fetchone()
    return dict(row) if row else None


def delete_gym(gym_id: int) -> bool:
    """El inventario y las preferencias se van por ON DELETE CASCADE. Los planes
    anclados NO se tocan: conservan el gym_id colgando y el borde HTTP los marca
    con `gym_missing` para que la UI ofrezca re-anclarlos."""
    with get_db() as conn:
        row = conn.execute("DELETE FROM gyms WHERE id = %s RETURNING id", (gym_id,)).fetchone()
    return row is not None


def duplicate_gym(gym_id: int, name: str | None = None) -> dict[str, Any] | None:
    source = get_gym(gym_id)
    if source is None:
        return None
    copy = create_gym(
        {**source, "name": name or unique_gym_copy_name(source["name"])}
    )
    ts = now_iso()
    with get_db() as conn:
        conn.execute(
            """
            INSERT INTO gym_equipment (gym_id, name, equipment_type, weight_kg, quantity, created_at)
            SELECT %s, name, equipment_type, weight_kg, quantity, %s
            FROM gym_equipment WHERE gym_id = %s
            """,
            (copy["id"], ts, gym_id),
        )
        conn.execute(
            """
            INSERT INTO gym_exercise_prefs (gym_id, exercise_id, state, created_at)
            SELECT %s, exercise_id, state, %s FROM gym_exercise_prefs WHERE gym_id = %s
            """,
            (copy["id"], ts, gym_id),
        )
    return copy


def resolve_gym_id(explicit: int | None = None) -> int | None:
    """El espacio que rige AHORA. Por orden:

      1. el que pida el cliente — es el cambio de espacio para una sesion
         suelta, que a proposito no se persiste en ningun sitio;
      2. el del plan activo;
      3. el primero que exista, para que nada reviente si el plan apunta a un
         espacio borrado o todavia no tiene ancla.

    Devuelve None solo si no hay ni un espacio, que tras bootstrap_gyms() no
    deberia pasar. No hay columna `is_default` a proposito: un flag puede
    desincronizarse del plan activo y crea la pregunta «cual gana» en cada
    endpoint.
    """
    if explicit is not None and gym_exists(explicit):
        return explicit
    active = get_active_plan()
    anchored = (active or {}).get("payload", {}).get("gym_id")
    if anchored is not None and gym_exists(anchored):
        return anchored
    with get_db() as conn:
        row = conn.execute("SELECT id FROM gyms ORDER BY id LIMIT 1").fetchone()
    return row["id"] if row else None


