TARGET_SESSIONS_PER_14D = 2  # how many hits/2wk a muscle "should" get for 100% coverage


def get_muscle_stats(start: str, end: str) -> dict[str, dict[str, Any]]:
    """Per-muscle sessions/volume/last-trained-date for [start, end], zero-filled
    for every muscle target in the catalog (not just ones with data) so
    never-trained groups show up correctly."""
    from . import catalog

    emap = catalog.exercise_map()
    all_targets = {e.get("target", "other") for e in emap.values()}
    stats: dict[str, dict[str, Any]] = {
        m: {"volume_kg": 0.0, "dates": set(), "last_date": None} for m in all_targets
    }

    with get_db() as conn:
        rows = conn.execute(
            """
            SELECT ss.exercise_id, s.date,
              CAST(SUM(ss.reps * COALESCE(ss.weight_kg, 0)) AS DOUBLE PRECISION) as volume
            FROM session_sets ss
            JOIN sessions s ON s.id = ss.session_id
            WHERE s.date BETWEEN %s AND %s AND ss.done = 1 AND s.completed = 1
            GROUP BY ss.exercise_id, s.date
            """,
            (start, end),
        ).fetchall()

    for row in rows:
        ex = emap.get(row["exercise_id"])
        if not ex:
            continue
        m = ex.get("target", "other")
        stats[m]["volume_kg"] += float(row["volume"] or 0)
        stats[m]["dates"].add(row["date"])
        if stats[m]["last_date"] is None or row["date"] > stats[m]["last_date"]:
            stats[m]["last_date"] = row["date"]

    return {
        m: {"volume_kg": s["volume_kg"], "sessions": len(s["dates"]), "last_date": s["last_date"]}
        for m, s in stats.items()
    }


def coverage_pct(sessions: int, window_days: int) -> int:
    target = TARGET_SESSIONS_PER_14D * (window_days / 14)
    return min(100, round(100 * sessions / target)) if target > 0 else 0


def count_prs_this_month(month_start: str, month_end: str) -> int:
    """A PR = an exercise's max weight in the window beats (or is the first
    time reaching) its all-time max weight from strictly before the window."""
    with get_db() as conn:
        # Postgres no admite alias del SELECT dentro de HAVING (a diferencia de
        # sqlite), asi que la condicion repite la expresion agregada completa.
        rows = conn.execute(
            """
            SELECT ss.exercise_id,
              MAX(CASE WHEN s.date >= %s AND s.date <= %s THEN ss.weight_kg END) as month_max,
              MAX(CASE WHEN s.date < %s THEN ss.weight_kg END) as prior_max
            FROM session_sets ss
            JOIN sessions s ON s.id = ss.session_id
            WHERE ss.weight_kg > 0 AND ss.done = 1
            GROUP BY ss.exercise_id
            HAVING MAX(CASE WHEN s.date >= %s AND s.date <= %s THEN ss.weight_kg END) IS NOT NULL
            """,
            (month_start, month_end, month_start, month_start, month_end),
        ).fetchall()
    return sum(1 for r in rows if r["prior_max"] is None or r["month_max"] > r["prior_max"])


def compute_weekly_load(start: str, end: str) -> dict[str, Any]:
    sessions = list_sessions(start, end)
    with get_db() as conn:
        runs = conn.execute(
            "SELECT * FROM runs WHERE date BETWEEN %s AND %s ORDER BY date",
            (start, end),
        ).fetchall()
        weights = conn.execute(
            "SELECT * FROM body_metrics WHERE date BETWEEN %s AND %s ORDER BY date",
            (start, end),
        ).fetchall()

    completed = [s for s in sessions if s["completed"]]
    volume = sum(float(s["volume_kg"] or 0) for s in completed)
    set_count = sum(int(s["set_count"] or 0) for s in completed)
    rpes = [s["session_rpe"] for s in completed if s.get("session_rpe")]
    set_rpes = [s["avg_set_rpe"] for s in completed if s.get("avg_set_rpe")]
    run_km = sum(float(r["distance_km"] or 0) for r in runs)
    avg_session_rpe = sum(rpes) / len(rpes) if rpes else None
    avg_set_rpe = sum(set_rpes) / len(set_rpes) if set_rpes else None

    # Simple strain index: volume tonnage + run load + RPE factor
    rpe_factor = (avg_session_rpe or avg_set_rpe or 5) / 10
    strain = round((volume / 1000) + (run_km * 2) + (len(completed) * 3 * rpe_factor), 1)

    return {
        "week_start": start,
        "week_end": end,
        "training_days": len(completed),
        "planned_or_logged_days": len(sessions),
        "total_volume_kg": round(volume, 1),
        "total_sets": set_count,
        "avg_session_rpe": round(avg_session_rpe, 1) if avg_session_rpe else None,
        "avg_set_rpe": round(avg_set_rpe, 1) if avg_set_rpe else None,
        "run_distance_km": round(run_km, 2),
        "run_count": len(runs),
        "strain_index": strain,
        "body_weights": [dict(w) for w in weights],
        "sessions": sessions,
        "runs": [dict(r) for r in runs],
    }
