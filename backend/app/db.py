def failed_login_counts(email: str, ip: str | None, since: str) -> tuple[int, int]:
    """(fallos de este email, fallos de esta IP) dentro de la ventana."""
    with get_db() as conn:
        by_email = conn.execute(
            "SELECT COUNT(*) AS n FROM auth_login_attempts "
            "WHERE email_lower = lower(%s) AND ok = 0 AND created_at > %s",
            (email.strip(), since),
        ).fetchone()["n"]
        by_ip = 0
        if ip:
            by_ip = conn.execute(
                "SELECT COUNT(*) AS n FROM auth_login_attempts "
                "WHERE ip = %s AND ok = 0 AND created_at > %s",
                (ip, since),
            ).fetchone()["n"]
        return int(by_email), int(by_ip)


# --- Admin inicial ---------------------------------------------------------

# Arbitrario y fijo. Sirve para que dos replicas arrancando a la vez no creen dos
# admins: un COUNT no es un cerrojo, esto si. Se libera al cerrar la transaccion.
_BOOTSTRAP_LOCK = 778501


def ensure_bootstrap_admin() -> int | None:
    """Envoltorio con su propia transaccion. La migracion usa _bootstrap_admin_in
    directamente para que todo caiga en el mismo BEGIN."""
    with get_db() as conn:
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (_BOOTSTRAP_LOCK,))
        return _bootstrap_admin_in(conn)


def _bootstrap_admin_in(conn: psycopg.Connection) -> int | None:
    """Crea el primer admin a partir de user_profile id=1 la primera vez. Es
    idempotente: en cuanto existe un usuario no vuelve a hacer nada nunca.

    Devuelve el id del admin, o None si no hay forma de determinar su email (base
    virgen sin perfil y sin COACHFIT_ADMIN_EMAIL). Ese caso NO es un error: una
    instalacion nueva puede arrancar sin usuarios y crearlos despues.
    """
    _load_env_file()
    existing = conn.execute("SELECT id FROM users ORDER BY id LIMIT 1").fetchone()
    if existing:
        return int(existing["id"])

    legacy = conn.execute("SELECT * FROM user_profile WHERE id = 1").fetchone()
    legacy = dict(legacy) if legacy else {}
    email = (
        os.getenv("COACHFIT_ADMIN_EMAIL", "").strip()
        or (legacy.get("email") or "").strip()
    )
    if not email:
        print(
            "[coachfit] No hay usuarios y user_profile.id=1 no tiene email. "
            "Define COACHFIT_ADMIN_EMAIL para crear el admin inicial.",
            flush=True,
        )
        return None

    configured = os.getenv("COACHFIT_ADMIN_PASSWORD", "").strip()
    plain = configured or auth.temporary_password()
    stamp = now_iso()
    row = conn.execute(
        f"""
        INSERT INTO users (
          email, password_hash, role, full_name, must_change_password,
          created_at, updated_at
        )
        VALUES (%s, %s, 'admin', %s, 1, %s, %s)
        ON CONFLICT (lower(email)) DO NOTHING
        RETURNING {_USER_COLS}
        """,
        (email, auth.hash_password(plain), legacy.get("full_name"), stamp, stamp),
    ).fetchone()
    if row is None:  # carrera perdida contra otro worker
        row = conn.execute(
            "SELECT id FROM users WHERE lower(email) = lower(%s)", (email,)
        ).fetchone()
        return int(row["id"]) if row else None

    admin_id = int(row["id"])

    # Copia del perfil singleton al perfil por usuario. Solo las columnas que
    # existen de verdad en la fila legada.
    carried = ["photo_object_key", "photo_content_type", "photo_original_name",
               "photo_size_bytes", *USER_PROFILE_EDITABLE_FIELDS]
    present = [c for c in carried if c in legacy]
    cols = ", ".join(("user_id", *present, "updated_at"))
    marks = ", ".join(["%s"] * (len(present) + 2))
    conn.execute(
        f"INSERT INTO user_profiles ({cols}) VALUES ({marks}) "
        "ON CONFLICT (user_id) DO NOTHING",
        (admin_id, *(legacy.get(c) for c in present), stamp),
    )

    if not configured:
        print("=" * 70, flush=True)
        print(f"  COACH FIT - admin creado: {email}", flush=True)
        print(f"  CONTRASENA TEMPORAL: {plain}", flush=True)
        print("  Se muestra UNA sola vez. Cambiala en el primer login.", flush=True)
        print("=" * 70, flush=True)
    return admin_id


# ---------------------------------------------------------------------------
# Migracion a multiusuario.
#
# No hay Alembic, pero Postgres ejecuta ALTER TABLE, CREATE/DROP INDEX y UPDATE
# DENTRO de transacciones. Toda esta funcion corre en un solo BEGIN...COMMIT:
# o entra entera o no entra nada. Esa es la respuesta a "que pasa si falla a
# medias": no queda un estado intermedio, el siguiente arranque reintenta desde
# cero con el esquema exactamente como estaba.
#
# ATENCION: es FORWARD-ONLY. Despues de que user_id sea NOT NULL, la imagen
# anterior hace INSERT INTO sessions (date, ...) sin user_id y viola la
# restriccion: todos los POST devolverian 500. Backup verificado antes.
# ---------------------------------------------------------------------------

# Las siete raices del grafo. Las demas tablas heredan la pertenencia por su FK
# ON DELETE CASCADE al padre: session_sets cuelga de sessions, body_metric_photos
# de body_metrics, gym_equipment y gym_exercise_prefs de gyms. Denormalizar el
# dueno ahi crearia un segundo sitio que se puede desincronizar y un segundo
# sitio donde olvidar el filtro.
OWNED_TABLES = (
    "sessions",
    "body_metrics",
    "runs",
    "coach_notes",
    "plans",
    "gyms",
    "user_equipment",
)

_MIGRATION_LOCK = 778502


def migrate_to_multiuser() -> None:
    """Migracion forward-only a aislamiento por usuario. La llama el startup
    (main.py), no init_db().

    Debe ir en el mismo despliegue que este db.py ya scoped: en cuanto los
    indices pasan a (user_id, lower(name)), un ON CONFLICT viejo peta al
    arrancar; y sin user_id en los INSERT el NOT NULL recien puesto falla.
    Backup verificado antes: el paso no se revierte con la imagen anterior.
    """
    with get_db() as conn:
        # Dos replicas arrancando a la vez: la segunda espera aqui y, cuando
        # entra, encuentra todo hecho y no hace nada. Un COUNT no es un cerrojo.
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (_MIGRATION_LOCK,))
        _add_user_id_columns(conn)
        admin_id = _bootstrap_admin_in(conn)
        if admin_id is None:
            # Base virgen sin forma de saber quien es el dueno. No se puede
            # hacer backfill ni poner NOT NULL; se reintentara cuando exista un
            # usuario. Los indices tampoco se cambian: seguirian sin poder
            # garantizar nada util con user_id a NULL.
            return
        _backfill_owner(conn, admin_id)
        _enforce_owner_not_null(conn)
        _swap_unique_indexes(conn)


def _add_user_id_columns(conn: psycopg.Connection) -> None:
    for table in OWNED_TABLES:
        # Sin DEFAULT es metadata-only en PG11+: no reescribe la tabla.
        conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS user_id INTEGER")
        # NOT VALID evita el ACCESS EXCLUSIVE largo del scan; VALIDATE lo hace
        # despues con un candado mas suave. A este volumen da igual, pero es
        # gratis y correcto.
        conn.execute(
            f"""
            DO $$ BEGIN
              ALTER TABLE {table} ADD CONSTRAINT {table}_user_fk
                FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE NOT VALID;
            EXCEPTION WHEN duplicate_object THEN NULL;
            END $$
            """
        )
        conn.execute(f"ALTER TABLE {table} VALIDATE CONSTRAINT {table}_user_fk")
        conn.execute(
            f"CREATE INDEX IF NOT EXISTS {table}_by_user ON {table} (user_id)"
        )


def _backfill_owner(conn: psycopg.Connection, admin_id: int) -> None:
    """Asigna al admin bootstrap todas las filas con user_id IS NULL.

    El legado de un solo usuario pertenece al admin inicial aunque ya existan
    mas cuentas (p.ej. un segundo usuario creado antes de migrar). Sin esto
    quedarian huerfanos y _enforce_owner_not_null abortaria la migracion.
    """
    for table in OWNED_TABLES:
        conn.execute(
            f"UPDATE {table} SET user_id = %s WHERE user_id IS NULL", (admin_id,)
        )


def _enforce_owner_not_null(conn: psycopg.Connection) -> None:
    for table in OWNED_TABLES:
        if table == "user_equipment":
            # Legado de solo lectura: nadie escribe ya ahi. Ponerle NOT NULL no
            # compra nada y anade un modo de fallo.
            continue
        orphans = conn.execute(
            f"SELECT COUNT(*) AS n FROM {table} WHERE user_id IS NULL"
        ).fetchone()["n"]
        if orphans:
            raise RuntimeError(
                f"{table}: {orphans} filas sin user_id tras el backfill. "
                "Aborto la migracion; la transaccion entera se revierte."
            )
        # No-op si ya lo es, asi que es idempotente.
        conn.execute(f"ALTER TABLE {table} ALTER COLUMN user_id SET NOT NULL")


def _swap_unique_indexes(conn: psycopg.Connection) -> None:
    """Los cuatro unicos globales pasan a ser unicos POR USUARIO.

    Esto y el cambio de los ON CONFLICT de bootstrap_gyms/bootstrap_plans van en
    el mismo commit obligatoriamente: en cuanto el indice cambia de forma, un
    `ON CONFLICT (lower(name))` lanza «there is no unique or exclusion constraint
    matching the ON CONFLICT specification» EN EL ARRANQUE y la app no levanta.
    """
    # sessions.date era UNIQUE global: una sola sesion por fecha en toda la base.
    # Ojo: upsert_session() hace SELECT-luego-INSERT, no ON CONFLICT, asi que si
    # esta constraint cayera sin que se cree la nueva NO fallaria — duplicaria el
    # dia en silencio. Por eso van juntas.
    conn.execute("ALTER TABLE sessions DROP CONSTRAINT IF EXISTS sessions_date_key")
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS sessions_user_date_unique "
        "ON sessions (user_id, date)"
    )

    conn.execute("DROP INDEX IF EXISTS plans_name_unique")
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS plans_user_name_unique "
        "ON plans (user_id, lower(name))"
    )

    # Un plan activo POR USUARIO, no uno en toda la base.
    conn.execute("DROP INDEX IF EXISTS plans_single_active")
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS plans_user_single_active "
        "ON plans (user_id) WHERE is_active = 1"
    )

    conn.execute("DROP INDEX IF EXISTS gyms_name_unique")
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS gyms_user_name_unique "
        "ON gyms (user_id, lower(name))"
    )


