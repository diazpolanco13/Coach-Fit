def count_gyms() -> int:
    with get_db() as conn:
        return conn.execute("SELECT COUNT(*) AS n FROM gyms").fetchone()["n"]


def list_gyms() -> list[dict[str, Any]]:
    """Espacios con sus contadores.

    Los COUNT van como subconsultas correlacionadas y NO como dos LEFT JOIN:
    unir equipo y preferencias en la misma consulta multiplica filas y cada
    COUNT saldria inflado por el cardinal del otro. Las tablas son diminutas,
    asi que la subconsulta sale gratis y ademas se lee.
    """
    with get_db() as conn:
        rows = conn.execute(
            """
            SELECT g.*,
              (SELECT COUNT(*) FROM gym_equipment e WHERE e.gym_id = g.id)
                AS equipment_count,
              (SELECT COUNT(*) FROM gym_exercise_prefs p
                 WHERE p.gym_id = g.id AND p.state = 'favorito') AS favorite_count,
              (SELECT COUNT(*) FROM gym_exercise_prefs p
                 WHERE p.gym_id = g.id AND p.state = 'oculto') AS hidden_count
            FROM gyms g ORDER BY g.id
            """
        ).fetchall()
    return [dict(r) for r in rows]


