def unique_copy_name(base: str) -> str:
    """«Piernas» -> «Piernas (copia)» -> «Piernas (copia 2)»... El indice unico
    sobre lower(name) es la verdad; esto solo evita el 409 obvio."""
    from . import plans as plans_mod

    stem = base.strip()[: plans_mod.MAX_NAME - 15]  # deja hueco para el sufijo
    with get_db() as conn:
        taken = {r["n"] for r in conn.execute("SELECT lower(name) AS n FROM plans").fetchall()}
    candidate, i = f"{stem} (copia)", 2
    while candidate.casefold() in taken:
        candidate, i = f"{stem} (copia {i})", i + 1
    return candidate


def _activate_in_conn(conn: psycopg.Connection, plan_id: int) -> bool:
    """El orden importa: primero se apaga el activo y despues se enciende el
    nuevo, porque el indice parcial plans_single_active no admite dos a la vez.
    Las dos sentencias van en la misma transaccion.

    No toca updated_at: activar no es editar, y ese orden se usa para elegir
    sucesor al borrar.
    """
    conn.execute("UPDATE plans SET is_active = 0 WHERE is_active = 1")
    row = conn.execute(
        "UPDATE plans SET is_active = 1 WHERE id = %s RETURNING id", (plan_id,)
    ).fetchone()
    return row is not None


def create_plan(name: str, payload: dict[str, Any], *, activate: bool = False) -> dict[str, Any]:
    from . import plans as plans_mod

    doc = plans_mod.normalize_plan_payload({**payload, "name": name})
    ts = now_iso()
    with get_db() as conn:
        row = conn.execute(
            """
            INSERT INTO plans (name, payload, is_active, created_at, updated_at)
            VALUES (%s, %s, 0, %s, %s) RETURNING *
            """,
            (doc["name"], json.dumps(doc, ensure_ascii=False), ts, ts),
        ).fetchone()
        if activate:
            _activate_in_conn(conn, row["id"])
            row = conn.execute("SELECT * FROM plans WHERE id = %s", (row["id"],)).fetchone()
    if activate:
        _mirror_active_to_week_plan()
    return _plan_row(row)


def update_plan(
    plan_id: int,
    *,
    name: str | None = None,
    payload: dict[str, Any] | None = None,
) -> dict[str, Any] | None:
    """Fusiona sobre el payload actual, para que un cliente que solo manda
    `days` no borre los objetivos del plan."""
    from . import plans as plans_mod

    current = get_plan(plan_id)
    if current is None:
        return None
    base = payload if payload is not None else current["payload"]
    doc = plans_mod.normalize_plan_payload(
        {**base, "name": name or base.get("name") or current["name"]}
    )
    with get_db() as conn:
        row = conn.execute(
            "UPDATE plans SET name = %s, payload = %s, updated_at = %s "
            "WHERE id = %s RETURNING *",
            (doc["name"], json.dumps(doc, ensure_ascii=False), now_iso(), plan_id),
        ).fetchone()
    if row is None:
        return None
    if row["is_active"]:
        _mirror_active_to_week_plan()
    return _plan_row(row)


