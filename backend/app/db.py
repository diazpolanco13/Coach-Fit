def delete_plan(plan_id: int) -> dict[str, Any]:
    """El caller ya comprobo que no es el ultimo plan. Si el borrado era el
    activo se activa el siguiente (el editado mas recientemente), para que nunca
    queden cero activos."""
    with get_db() as conn:
        row = conn.execute(
            "DELETE FROM plans WHERE id = %s RETURNING is_active", (plan_id,)
        ).fetchone()
        if row is None:
            return {"deleted": None, "active_id": None}
        if row["is_active"]:
            nxt = conn.execute(
                "SELECT id FROM plans ORDER BY updated_at DESC, id DESC LIMIT 1"
            ).fetchone()
            if nxt:
                _activate_in_conn(conn, nxt["id"])
        active = conn.execute("SELECT id FROM plans WHERE is_active = 1").fetchone()
    _mirror_active_to_week_plan()
    return {"deleted": plan_id, "active_id": active["id"] if active else None}


