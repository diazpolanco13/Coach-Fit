def unique_gym_copy_name(base: str) -> str:
    from . import gyms as gyms_mod

    stem = base.strip()[: gyms_mod.MAX_GYM_NAME - 15]
    uid = require_uid()
    with get_db() as conn:
        taken = {
            r["n"]
            for r in conn.execute(
                "SELECT lower(name) AS n FROM gyms WHERE user_id = %s", (uid,)
            ).fetchall()
        }
    candidate, i = f"{stem} (copia)", 2
    while candidate.casefold() in taken:
        candidate, i = f"{stem} (copia {i})", i + 1
    return candidate


