        """
        SELECT id FROM body_metrics
        WHERE user_id = %s AND date = %s
          AND (measured_at = %s::text OR measured_at IS NULL)
        ORDER BY measured_at DESC NULLS LAST, id DESC
        LIMIT 1
        """,
        (uid, payload["date"], payload.get("measured_at")),
