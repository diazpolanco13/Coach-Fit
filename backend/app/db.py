def update_plan(
    plan_id: int,
    *,
    name: str | None = None,
    payload: dict[str, Any] | None = None,
) -> dict[str, Any] | None:
    """Fusiona sobre el payload actual, para que un cliente que solo manda
    `days` no borre los objetivos del plan."""
    from . import plans as plans_mod

    uid = require_uid()
