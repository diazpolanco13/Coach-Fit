def bootstrap_gyms() -> None:
    """Idempotente: corre en cada arranque y solo hace algo la primera vez.

    1. Si `gyms` esta vacia, crea el espacio «Casa» y copia dentro TODO el
       inventario global de `user_equipment` — que en produccion tiene el equipo
       real del usuario. Las filas viejas NO se borran ni se modifican:
       user_equipment queda como legado de solo lectura, igual que week_plan.
    2. Si user_equipment tambien estaba vacia (base recien creada), siembra
       DEFAULT_EQUIPMENT directamente dentro del espacio.
    3. No toca los planes: un plan sin `gym_id` lo resuelve resolve_gym_id() al
       primer espacio, asi que no hace falta reescribir ningun payload guardado.

    Todo va en UNA sola transaccion, a diferencia de bootstrap_plans(): aqui la
    guarda y la escritura no se pueden separar. Una caida entre medias dejaria
    un espacio vacio que la guarda del COUNT ya daria por sembrado, y el equipo
    del usuario no se copiaria jamas.
    """
    from . import gyms as gyms_mod

    with get_db() as conn:
        if conn.execute("SELECT COUNT(*) AS n FROM gyms").fetchone()["n"]:
            return

        ts = now_iso()
        legacy = conn.execute(
            """
            SELECT name, equipment_type, weight_kg,
                   COALESCE(quantity, 1) AS quantity, created_at
            FROM user_equipment ORDER BY id
            """
        ).fetchall()

        # ON CONFLICT + RETURNING: si dos workers arrancan a la vez, el segundo
        # choca contra gyms_name_unique, no devuelve fila y se va sin sembrar.
        # El COUNT de arriba no es un cerrojo; el indice unico si.
        gym = conn.execute(
            """
            INSERT INTO gyms (name, kind, icon, created_at, updated_at)
            VALUES (%s, %s, %s, %s, %s)
            ON CONFLICT (lower(name)) DO NOTHING
            RETURNING id
            """,
            (
                gyms_mod.DEFAULT_GYM_NAME,
                gyms_mod.DEFAULT_KIND,
                gyms_mod.DEFAULT_GYM_ICON,
                # created_at hereda la fecha del equipo mas antiguo: el espacio
                # no nacio el dia del despliegue. Las fechas son ISO en TEXT, asi
                # que el orden lexicografico es el cronologico.
                min((r["created_at"] for r in legacy), default=ts),
                ts,
            ),
        ).fetchone()
        if gym is None:
            return

        rows: list[dict[str, Any]] = [dict(r) for r in legacy] or [
            {"name": n, "equipment_type": t, "weight_kg": w, "quantity": q, "created_at": ts}
            for n, t, w, q in DEFAULT_EQUIPMENT
        ]
        for r in rows:
            conn.execute(
                """
                INSERT INTO gym_equipment
                  (gym_id, name, equipment_type, weight_kg, quantity, created_at)
                VALUES (%s, %s, %s, %s, %s, %s)
                """,
                (
                    gym["id"], r["name"], r["equipment_type"],
                    r["weight_kg"], r["quantity"], r["created_at"],
                ),
            )


